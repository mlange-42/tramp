// Command gen converts the Maki SVG icons in ../maki to IconVG, and writes them to ../icons_gen.go.
//
// Run it with go generate in the symbols package. It supports the subset of SVG used by Maki:
// one or more <path> elements with path data, filled with the nonzero rule.
package main

import (
	"bytes"
	"encoding/xml"
	"fmt"
	"go/format"
	"log"
	"math"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"golang.org/x/exp/shiny/iconvg"
	"golang.org/x/image/math/f32"
)

func main() {
	files, err := filepath.Glob(filepath.Join("maki", "*.svg"))
	if err != nil {
		log.Fatal(err)
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by gen/main.go from the Maki icons in maki/. DO NOT EDIT.\n\n")
	out.WriteString("package symbols\n\n")
	out.WriteString("// makiIcons are the Maki icons in IconVG format, by name.\n")
	out.WriteString("var makiIcons = map[string][]byte{\n")
	for _, f := range files {
		data, err := convert(f)
		if err != nil {
			log.Fatalf("%s: %v", f, err)
		}
		name := strings.TrimSuffix(filepath.Base(f), ".svg")
		fmt.Fprintf(&out, "%q: {", name)
		for i, b := range data {
			if i%16 == 0 {
				out.WriteString("\n")
			}
			fmt.Fprintf(&out, "%#02x, ", b)
		}
		out.WriteString("\n},\n")
	}
	out.WriteString("}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("icons_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

type svg struct {
	ViewBox string `xml:"viewBox,attr"`
	Paths   []struct {
		D string `xml:"d,attr"`
	} `xml:"path"`
}

// convert reads an SVG file and returns it as IconVG.
func convert(file string) ([]byte, error) {
	src, err := os.ReadFile(file)
	if err != nil {
		return nil, err
	}
	var s svg
	if err := xml.Unmarshal(src, &s); err != nil {
		return nil, err
	}
	var vb [4]float32
	fields := strings.Fields(strings.ReplaceAll(s.ViewBox, ",", " "))
	if len(fields) != 4 {
		return nil, fmt.Errorf("invalid viewBox %q", s.ViewBox)
	}
	for i, f := range fields {
		v, err := strconv.ParseFloat(f, 32)
		if err != nil {
			return nil, err
		}
		vb[i] = float32(v)
	}
	if len(s.Paths) == 0 {
		return nil, fmt.Errorf("no paths")
	}
	var enc iconvg.Encoder
	enc.Reset(iconvg.Metadata{
		ViewBox: iconvg.Rectangle{Min: f32.Vec2{vb[0], vb[1]}, Max: f32.Vec2{vb[0] + vb[2], vb[1] + vb[3]}},
		Palette: iconvg.DefaultPalette,
	})
	for _, p := range s.Paths {
		if err := encodePath(&enc, p.D); err != nil {
			return nil, err
		}
	}
	return enc.Bytes()
}

// encodePath encodes SVG path data. All coordinates are converted to absolute ones,
// and smooth curves to explicit ones.
func encodePath(enc *iconvg.Encoder, d string) error {
	sc := scanner{s: d}
	var (
		cur, start [2]float32
		// ctrl is the last control point of a cubic or quadratic curve, for smooth curves.
		ctrl     [2]float32
		lastCmd  byte
		started  bool // a path was started with StartPath
		open     bool // a subpath is open, with a current point
		closed   bool // the last subpath was closed, and no new one started
		cmd      byte
		haveCmd  bool
		moveNext bool // the next coordinate pair of an M command is a moveto
	)
	moveTo := func(p [2]float32) {
		if !started {
			enc.StartPath(0, p[0], p[1])
			started = true
		} else {
			enc.ClosePathAbsMoveTo(p[0], p[1])
		}
		cur, start, open, closed = p, p, true, false
	}
	// ensureOpen starts a new subpath at the current point after a close without moveto.
	ensureOpen := func() error {
		if closed {
			moveTo(cur)
		}
		if !open {
			return fmt.Errorf("drawing without current point")
		}
		return nil
	}
	for {
		sc.skipSpace()
		if sc.done() {
			break
		}
		if c := sc.peek(); isCommand(c) {
			cmd, haveCmd = c, true
			sc.i++
			moveNext = cmd == 'M' || cmd == 'm'
			if cmd == 'Z' || cmd == 'z' {
				if !open {
					return fmt.Errorf("close without subpath")
				}
				cur, closed, open = start, true, true
				lastCmd = 'Z'
				continue
			}
		} else if !haveCmd || cmd == 'Z' || cmd == 'z' {
			return fmt.Errorf("unexpected %q at %d", c, sc.i)
		}

		rel := cmd >= 'a'
		abs := func(p [2]float32) [2]float32 {
			if rel {
				return [2]float32{cur[0] + p[0], cur[1] + p[1]}
			}
			return p
		}
		upper := cmd &^ 0x20
		switch upper {
		case 'M':
			p, err := sc.pair()
			if err != nil {
				return err
			}
			if moveNext {
				if rel && !open {
					rel = false
				}
				moveTo(abs(p))
				moveNext = false
				lastCmd = 'M'
				continue
			}
			// Further pairs are lineto.
			if err := ensureOpen(); err != nil {
				return err
			}
			cur = abs(p)
			enc.AbsLineTo(cur[0], cur[1])
		case 'L':
			p, err := sc.pair()
			if err != nil {
				return err
			}
			if err := ensureOpen(); err != nil {
				return err
			}
			cur = abs(p)
			enc.AbsLineTo(cur[0], cur[1])
		case 'H', 'V':
			v, err := sc.number()
			if err != nil {
				return err
			}
			if err := ensureOpen(); err != nil {
				return err
			}
			i := 0
			if upper == 'V' {
				i = 1
			}
			if rel {
				cur[i] += v
			} else {
				cur[i] = v
			}
			enc.AbsLineTo(cur[0], cur[1])
		case 'C', 'S':
			var c1 [2]float32
			if upper == 'C' {
				p, err := sc.pair()
				if err != nil {
					return err
				}
				c1 = abs(p)
			} else if lastCmd == 'C' {
				c1 = [2]float32{2*cur[0] - ctrl[0], 2*cur[1] - ctrl[1]}
			} else {
				c1 = cur
			}
			p2, err := sc.pair()
			if err != nil {
				return err
			}
			p, err := sc.pair()
			if err != nil {
				return err
			}
			if err := ensureOpen(); err != nil {
				return err
			}
			c2, end := abs(p2), abs(p)
			enc.AbsCubeTo(c1[0], c1[1], c2[0], c2[1], end[0], end[1])
			cur, ctrl = end, c2
			lastCmd = 'C'
			continue
		case 'Q', 'T':
			var c1 [2]float32
			if upper == 'Q' {
				p, err := sc.pair()
				if err != nil {
					return err
				}
				c1 = abs(p)
			} else if lastCmd == 'Q' {
				c1 = [2]float32{2*cur[0] - ctrl[0], 2*cur[1] - ctrl[1]}
			} else {
				c1 = cur
			}
			p, err := sc.pair()
			if err != nil {
				return err
			}
			if err := ensureOpen(); err != nil {
				return err
			}
			end := abs(p)
			enc.AbsQuadTo(c1[0], c1[1], end[0], end[1])
			cur, ctrl = end, c1
			lastCmd = 'Q'
			continue
		case 'A':
			rx, err := sc.number()
			if err != nil {
				return err
			}
			ry, err := sc.number()
			if err != nil {
				return err
			}
			rot, err := sc.number()
			if err != nil {
				return err
			}
			large, err := sc.flag()
			if err != nil {
				return err
			}
			sweep, err := sc.flag()
			if err != nil {
				return err
			}
			p, err := sc.pair()
			if err != nil {
				return err
			}
			if err := ensureOpen(); err != nil {
				return err
			}
			end := abs(p)
			if end != cur {
				enc.AbsArcTo(float32(math.Abs(float64(rx))), float32(math.Abs(float64(ry))), rot, large, sweep, end[0], end[1])
			}
			cur = end
		default:
			return fmt.Errorf("unsupported command %q", cmd)
		}
		lastCmd = upper
	}
	if !started {
		return fmt.Errorf("empty path")
	}
	enc.ClosePathEndPath()
	return nil
}

func isCommand(c byte) bool {
	return strings.IndexByte("MmLlHhVvCcSsQqTtAaZz", c) >= 0
}

// scanner reads numbers from SVG path data.
type scanner struct {
	s string
	i int
}

func (s *scanner) done() bool { return s.i >= len(s.s) }
func (s *scanner) peek() byte { return s.s[s.i] }

func (s *scanner) skipSpace() {
	for !s.done() && strings.IndexByte(" \t\r\n,", s.peek()) >= 0 {
		s.i++
	}
}

// number reads a number like "-1.5e-3". A second dot or a sign starts the next number, as in ".5.5" or "1-2".
func (s *scanner) number() (float32, error) {
	s.skipSpace()
	j := s.i
	if j < len(s.s) && (s.s[j] == '-' || s.s[j] == '+') {
		j++
	}
	dot, digits := false, false
	for ; j < len(s.s); j++ {
		c := s.s[j]
		if c >= '0' && c <= '9' {
			digits = true
		} else if c == '.' && !dot {
			dot = true
		} else {
			break
		}
	}
	if digits && j < len(s.s) && (s.s[j] == 'e' || s.s[j] == 'E') {
		k := j + 1
		if k < len(s.s) && (s.s[k] == '-' || s.s[k] == '+') {
			k++
		}
		if k < len(s.s) && s.s[k] >= '0' && s.s[k] <= '9' {
			for k < len(s.s) && s.s[k] >= '0' && s.s[k] <= '9' {
				k++
			}
			j = k
		}
	}
	if !digits {
		return 0, fmt.Errorf("expected number at %d in %q", s.i, s.s)
	}
	v, err := strconv.ParseFloat(s.s[s.i:j], 32)
	s.i = j
	return float32(v), err
}

func (s *scanner) pair() ([2]float32, error) {
	x, err := s.number()
	if err != nil {
		return [2]float32{}, err
	}
	y, err := s.number()
	return [2]float32{x, y}, err
}

// flag reads an arc flag, which may be written without separator, as in "a1 1 0 011 1".
func (s *scanner) flag() (bool, error) {
	s.skipSpace()
	if s.done() || (s.peek() != '0' && s.peek() != '1') {
		return false, fmt.Errorf("expected flag at %d in %q", s.i, s.s)
	}
	f := s.peek() == '1'
	s.i++
	return f, nil
}
